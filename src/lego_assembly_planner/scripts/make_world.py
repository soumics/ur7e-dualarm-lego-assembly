#!/usr/bin/env python3
"""Generate a build world + inventory for a target structure.

    python3 make_world.py ../models/house_door.ldr --out ~/ws/experiments/configs/house_door

Writes <out>/world.sdf (workcell world: lighting, plugins, central baseplate, loose
inventory bricks in each arm's supply grid) and <out>/inventory.json (for the planner).

Inventory = exactly the bricks the target needs, alternated between the left and right
supply grids per (type, colour). Every resting brick costs simulation speed (measured:
~24 resting bricks -> ~0.5x real time without robots), so there are no spares; this fixes
which arm handles which brick and leaves the planner to optimise order and timing.
"""

import argparse
import json
import math
import os
import sys
from collections import defaultdict

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from lego_assembly_planner.ldraw import read_ldr  # noqa: E402
from lego_assembly_planner.structure import LDU, STUD  # noqa: E402

TABLE_Z = 0.75
PLATE_H = 0.0032
PLATES = (8, 16)                       # available square baseplates (studs)
# Supply grid per arm: columns at |x| (arm side), rows in y. Bricks lie at yaw 0.
# Every slot is >= 0.33 m from the arm base (at |x| = 0.65): closer than ~0.25 m the arm
# cannot reach down to the table with the 154 mm 2FG7 (measured: pick at 0.23 m failed).
SUPPLY_X = (0.32, 0.24)
SUPPLY_Y = (-0.24, -0.12, 0.0, 0.12, 0.24)

HEADER = """<?xml version="1.0"?>
<!-- Generated by lego_assembly_planner/scripts/make_world.py for target "{name}". -->
<sdf version="1.9">
  <world name="lego_world">
    <physics name="1ms" type="ignored">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
    </physics>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="lego_grasp_lock" name="lego::GraspLock"><topic>/lego/grasp_lock</topic></plugin>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <scene><ambient>0.6 0.6 0.6 1</ambient><background>0.75 0.8 0.85 1</background><grid>false</grid></scene>
    <light type="directional" name="sun">
      <cast_shadows>true</cast_shadows><pose>0 0 10 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse><specular>0.3 0.3 0.3 1</specular><direction>-0.4 0.2 -0.9</direction>
    </light>
    <model name="ground_plane"><static>true</static><link name="link">
      <collision name="collision"><geometry><plane><normal>0 0 1</normal><size>20 20</size></plane></geometry></collision>
      <visual name="visual"><geometry><plane><normal>0 0 1</normal><size>20 20</size></plane></geometry>
        <material><ambient>0.5 0.5 0.5 1</ambient><diffuse>0.5 0.5 0.5 1</diffuse></material></visual>
    </link></model>
"""


def include(name, uri, x, y, z, yaw=0.0):
    return (f"    <include><name>{name}</name><uri>model://{uri}</uri>"
            f"<pose>{x:.4f} {y:.4f} {z:.4f} 0 0 {yaw:.4f}</pose></include>\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("target")
    ap.add_argument("--out", required=True)
    ap.add_argument("--plate-x", type=float, default=0.0)
    ap.add_argument("--plate-y", type=float, default=0.0)
    args = ap.parse_args()

    s = read_ldr(args.target)
    # smallest baseplate covering the footprint
    ext = max(max(abs(b.x) + b.half_extents[0], abs(b.y) + b.half_extents[1]) for b in s.bricks.values())
    plate = next((p for p in PLATES if p * STUD / 2 >= ext - 1e-6), None)
    if plate is None:
        raise SystemExit(f"structure too large for the available baseplates ({ext * LDU:.3f} m half-extent)")

    need = defaultdict(int)
    for b in sorted(s.bricks.values(), key=lambda b: b.id):
        need[(b.type, b.colour)] += 1
    slots = {"left": [(-x, y) for x in SUPPLY_X for y in SUPPLY_Y],
             "right": [(x, -y) for x in SUPPLY_X for y in SUPPLY_Y]}
    inventory, body, side_turn = [], [], 0
    for (typ, col), n in sorted(need.items()):
        for k in range(n):
            arm = ("left", "right")[(k + side_turn) % 2]
            if not slots[arm]:
                arm = "right" if arm == "left" else "left"
            if not slots[arm]:
                raise SystemExit("supply grids full")
            x, y = slots[arm].pop(0)
            name = f"lego_{typ}_{col}_{k}"
            inventory.append({"name": name, "type": typ, "colour": col, "arm": arm, "x": x, "y": y})
            body.append(include(name, f"lego_brick_{typ}_{col}", x, y, TABLE_Z))
        side_turn += n                      # balance odd counts across types

    plate_name = "baseplate_center"
    body.insert(0, include(plate_name, f"lego_baseplate_{plate}x{plate}", args.plate_x, args.plate_y, TABLE_Z))
    os.makedirs(args.out, exist_ok=True)
    with open(os.path.join(args.out, "world.sdf"), "w") as f:
        f.write(HEADER.format(name=s.name) + "".join(body) + "  </world>\n</sdf>\n")
    with open(os.path.join(args.out, "inventory.json"), "w") as f:
        json.dump({"target": os.path.abspath(args.target),
                   "baseplate": {"name": plate_name, "link": "plate", "x": args.plate_x, "y": args.plate_y,
                                 "z_top": TABLE_Z + PLATE_H, "studs": plate},
                   "bricks": inventory}, f, indent=2)
    per_arm = {a: sum(1 for i in inventory if i["arm"] == a) for a in ("left", "right")}
    print(f"{s.name}: {len(inventory)} inventory bricks {per_arm}, {plate}x{plate} baseplate -> {args.out}")


if __name__ == "__main__":
    main()
