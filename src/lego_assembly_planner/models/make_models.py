#!/usr/bin/env python3
"""Writes the example target structures as LDraw files (the planner's input format;
real designs would come from LeoCAD / BrickLink Studio exports instead).

Coordinates in LDU, LDraw axes (y down): brick at level L has y = -24 * (L + 1).
x along the baseplate's x, z along its y. Yaw 0: part x along world x; yaw 90: along y.
"""

import os

COL = {"red": 4, "blue": 1, "yellow": 14, "green": 2, "white": 15}
ROT = {0: "1 0 0 0 1 0 0 0 1", 90: "0 0 1 0 1 0 -1 0 0"}   # 90: part x -> world z (= our y)


def line(colour, x, level, z, yaw, part="3001"):
    return f"1 {COL[colour]} {x} {-24 * (level + 1)} {z} {ROT[yaw]} {part}.dat"


def write(name, lines, title):
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), f"{name}.ldr")
    with open(path, "w") as f:
        f.write(f"0 {title}\n0 Name: {name}.ldr\n0 Author: generated by make_models.py\n")
        f.write("\n".join(lines) + "\n")
    print("wrote", path)


write("tower2", [line("red", 0, 0, 0, 0), line("yellow", 0, 1, 0, 0)], "Two-brick tower")

wall = []
for lvl in range(3):
    xs = (-80, 0, 80) if lvl % 2 == 0 else (-40, 40)
    for i, x in enumerate(xs):
        wall.append(line(("red", "white")[(lvl + i) % 2], x, lvl, 0, 0))
write("wall", wall, "Staggered wall, 3 levels")

# Closed ring: kept as a negative test. A parallel side-gripper cannot close a ring of
# tightly fitted bricks (the last brick of any level has neighbours on both gripped sides),
# so the planner must reject it.
house = []
for lvl in range(3):
    c = ("red", "white", "red")[lvl]
    if lvl % 2 == 0:
        house += [line(c, x, lvl, z, 0) for z in (-60, 60) for x in (-40, 40)]   # front/back rows
        house += [line(c, x, lvl, 0, 90) for x in (-60, 60)]                      # side walls
    else:
        house += [line(c, 0, lvl, z, 0) for z in (-60, 60)]
        house += [line(c, x, lvl, z, 90) for x in (-60, 60) for z in (-40, 40)]
write("house_closed", house, "Closed 8x8 house walls (NOT buildable with a side gripper)")

# 8x8-stud house with a full-height 2-stud doorway in the front wall (x 0..40 LDU), so every
# level's ring stays open. Interleaved corners: levels 0 and 2 run the front/back walls
# through the corners, level 1 runs the side walls through them. Fits an 8x8 baseplate.
def P(part, colour, x, lvl, z, yaw):
    return line(colour, x, lvl, z, yaw, part)

house = []
for lvl in (0, 2):
    c = ("red", None, "white")[lvl]
    house += [P("3001", c, -40, lvl, -60, 0),          # front wall left of the door
              P("3003", c, 60, lvl, -60, 0),           # front wall right of the door (2x2)
              P("3001", c, -40, lvl, 60, 0), P("3001", c, 40, lvl, 60, 0),   # back wall
              P("3001", c, -60, lvl, 0, 90), P("3001", c, 60, lvl, 0, 90)]   # side walls
lvl = 1
house += [P("3003", "yellow", -20, lvl, -60, 0),       # front wall left of the door (2x2)
          P("3001", "yellow", -60, lvl, -40, 90), P("3001", "yellow", -60, lvl, 40, 90),
          P("3001", "yellow", 60, lvl, -40, 90), P("3001", "yellow", 60, lvl, 40, 90),
          P("3001", "yellow", 0, lvl, 60, 0)]          # back wall
write("house_door", house, "House walls with a doorway, 8x8 studs, 3 levels")
