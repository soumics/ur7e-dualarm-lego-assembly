#!/usr/bin/env python3
"""Generate Gazebo models for LEGO bricks at real dimensions.

    python3 scripts/generate_bricks.py        # writes models/lego_brick_<type>_<color>/

Geometry (LEGO lattice): stud pitch 8.0 mm, body = studs * 8.0 - 0.2 mm,
brick height 9.6 mm, stud 4.8 mm diameter x 1.7 mm. Model origin = bottom-face
centre, x along the long side.

Collision is hollow underneath, like a real brick, so bricks stack on studs:
1.0 mm top plate, outer walls, and between the stud positions either tubes
(2-wide bricks) or pins (1-wide bricks). Wall thickness and tube/pin radii are
derived from the lattice so a stud below just touches wall and tube, minus a
CLEARANCE: studs then lock the brick laterally onto the 8 mm grid (alignment).
Real LEGO clutch is an interference fit, which rigid-body physics cannot
reproduce; with the clearance, bricks align but do not clutch (handled
separately, see docs/GRIPPER_DECISION.md / PROGRESS.md Phase 4).
Mass: scaled from a 2x4 brick (2.3 g) by stud count.

Also generates a static baseplate (lego_baseplate_<w>x<l>): 3.2 mm plate with studs.

Bricks in a world must be named lego_<type>_<color>_<index> (lego_perception
relies on it), e.g. <name>lego_2x4_red_0</name> with uri model://lego_brick_2x4_red.
"""

import os

PITCH = 0.008
HEIGHT = 0.0096
STUD_R = 0.0024
STUD_H = 0.0017
TOP = 0.0010          # top plate thickness
# Stud-to-wall / stud-to-tube clearance. Real LEGO is an interference fit, but rounded stud
# edges guide a brick in over ~0.3 mm; these rigid, sharp-edged models have no lead-in, so a
# small clearance stands in for it. 0.05 mm proved harsher than reality (held bricks 0.06-0.07 mm
# off failed to seat in Phase 5), 0.10 mm is still well inside the real guidance region.
CLEARANCE = 0.0001
EDGE = 0.0001         # half the 0.2 mm gap between neighbouring bricks
WALL = (PITCH / 2 - EDGE) - STUD_R - CLEARANCE                    # outer edge -> stud surface
TUBE_R = (2 ** 0.5) * PITCH / 2 - STUD_R - CLEARANCE              # 2-wide: tube between 4 studs
PIN_R = PITCH / 2 - STUD_R - CLEARANCE                            # 1-wide: pin between 2 studs
PLATE_H = 0.0032
# Outer collision faces are inset by this much (visuals keep the real size). Real bricks sit
# 0.2 mm apart end to end; a welded brick on a position-controlled simulated arm wobbles
# ~0.1 mm sideways while stepping down and grazed neighbours at 0.2 mm (Phase 5). Inset ->
# 0.4 mm collision gap. Inner faces are unchanged, so stud alignment is unaffected.
OUTER_INSET = 0.0001
MASS_PER_STUD = 0.0023 / 8

TYPES = [(2, 4), (2, 2), (1, 2), (1, 4), (2, 6)]
BASEPLATES = [(8, 8), (16, 16)]
COLORS = {
    "red": (0.80, 0.05, 0.05),
    "blue": (0.05, 0.25, 0.80),
    "yellow": (0.95, 0.80, 0.05),
    "green": (0.10, 0.55, 0.15),
    "white": (0.92, 0.92, 0.92),
}


FRICTION = "<surface><friction><ode><mu>0.8</mu><mu2>0.8</mu2></ode></friction></surface>"
# Contact points per collision shape (SDF default 10). Hollow bricks have ~16 shapes;
# uncapped, a few resting bricks drop the simulation far below real time.
MAX_CONTACTS = int(os.environ.get("LEGO_MAX_CONTACTS", "10"))
MC = f"<max_contacts>{MAX_CONTACTS}</max_contacts>"
# Tubes/pins and the two short end walls stop LIFT short of the brick bottom, so on a
# flat surface only the two long walls carry load (8 contacts instead of ~28). They still
# guide the studs laterally. Measured: the contact solver cost grows steeply with the
# number of simultaneous contacts.
LIFT = float(os.environ.get("LEGO_LIFT", "0.0001"))


def baseplate_sdf(name, w, l):
    """Static plate, w x l studs, 3.2 mm thick, studs on top. Origin = bottom-face centre."""
    sx, sy = l * PITCH - 0.0002, w * PITCH - 0.0002
    zs = PLATE_H + STUD_H / 2
    geo = f"<geometry><cylinder><radius>{STUD_R}</radius><length>{STUD_H}</length></cylinder></geometry>"
    mat = "<material><ambient>0.35 0.6 0.35 1</ambient><diffuse>0.35 0.6 0.35 1</diffuse></material>"
    studs = []
    for i in range(l):
        for j in range(w):
            x, y = (i - (l - 1) / 2) * PITCH, (j - (w - 1) / 2) * PITCH
            studs.append(f'      <collision name="stud_{i}_{j}"><pose>{x:.4f} {y:.4f} {zs:.5f} 0 0 0</pose>{geo}{FRICTION}</collision>')
            studs.append(f'      <visual name="v_stud_{i}_{j}"><pose>{x:.4f} {y:.4f} {zs:.5f} 0 0 0</pose>{geo}{mat}</visual>')
    stud_xml = "\n".join(studs)
    return f"""<?xml version="1.0"?>
<!-- Generated by lego_dualarm_description/scripts/generate_bricks.py; do not edit by hand. -->
<sdf version="1.9">
  <model name="{name}">
    <static>true</static>
    <link name="plate">
      <collision name="body">
        <pose>0 0 {PLATE_H / 2} 0 0 0</pose>
        <geometry><box><size>{sx:.4f} {sy:.4f} {PLATE_H}</size></box></geometry>{FRICTION}
      </collision>
      <visual name="v_body">
        <pose>0 0 {PLATE_H / 2} 0 0 0</pose>
        <geometry><box><size>{sx:.4f} {sy:.4f} {PLATE_H}</size></box></geometry>{mat}
      </visual>
{stud_xml}
    </link>
  </model>
</sdf>
"""


def model_sdf(name, w, l, rgb):
    """w studs along y, l studs along x."""
    sx, sy = l * PITCH - 0.0002, w * PITCH - 0.0002
    m = MASS_PER_STUD * w * l
    ixx = m * (sy ** 2 + HEIGHT ** 2) / 12
    iyy = m * (sx ** 2 + HEIGHT ** 2) / 12
    izz = m * (sx ** 2 + sy ** 2) / 12
    def box(name, x, y, z, bx, by, bz):
        return (f'      <collision name="{name}">{MC}<pose>{x:.5f} {y:.5f} {z:.5f} 0 0 0</pose>'
                f'<geometry><box><size>{bx:.5f} {by:.5f} {bz:.5f}</size></box></geometry>{FRICTION}</collision>')

    def cyl(name, x, y, z, r, h):
        return (f'      <collision name="{name}">{MC}<pose>{x:.5f} {y:.5f} {z:.5f} 0 0 0</pose>'
                f'<geometry><cylinder><radius>{r:.5f}</radius><length>{h:.5f}</length></cylinder></geometry>'
                f'{FRICTION}</collision>')

    wall_h = HEIGHT - TOP
    short_h = wall_h - LIFT
    cx, cy = sx - 2 * OUTER_INSET, sy - 2 * OUTER_INSET     # collision outer size
    wt = WALL - OUTER_INSET                                   # wall thickness, inner face unchanged
    under = [
        box("top", 0, 0, HEIGHT - TOP / 2, cx, cy, TOP),
        box("wall_py", 0, cy / 2 - wt / 2, wall_h / 2, cx, wt, wall_h),
        box("wall_ny", 0, -cy / 2 + wt / 2, wall_h / 2, cx, wt, wall_h),
        box("wall_px", cx / 2 - wt / 2, 0, LIFT + short_h / 2, wt, cy - 2 * wt, short_h),
        box("wall_nx", -cx / 2 + wt / 2, 0, LIFT + short_h / 2, wt, cy - 2 * wt, short_h),
    ]
    # Tubes (2-wide) / pins (1-wide) sit between neighbouring stud positions along x
    r_post = TUBE_R if w == 2 else PIN_R
    if w in (1, 2):
        for i in range(l - 1):
            x = (i - (l - 2) / 2) * PITCH
            under.append(cyl(f"post_{i}", x, 0, LIFT + short_h / 2, r_post, short_h))
    under_xml = "\n".join(under)

    mat = (f"<material><ambient>{rgb[0]} {rgb[1]} {rgb[2]} 1</ambient>"
           f"<diffuse>{rgb[0]} {rgb[1]} {rgb[2]} 1</diffuse>"
           f"<specular>0.3 0.3 0.3 1</specular></material>")
    zc, zs = HEIGHT / 2, HEIGHT + STUD_H / 2
    studs = []
    for i in range(l):
        for j in range(w):
            x = (i - (l - 1) / 2) * PITCH
            y = (j - (w - 1) / 2) * PITCH
            geo = f"<geometry><cylinder><radius>{STUD_R}</radius><length>{STUD_H}</length></cylinder></geometry>"
            k = len(studs) // 2
            studs.append(f'      <collision name="stud_{k}">{MC}<pose>{x:.4f} {y:.4f} {zs:.5f} 0 0 0</pose>{geo}{FRICTION}</collision>')
            studs.append(f'      <visual name="v_stud_{k}"><pose>{x:.4f} {y:.4f} {zs:.5f} 0 0 0</pose>{geo}{mat}</visual>')
    stud_xml = "\n".join(studs)
    return f"""<?xml version="1.0"?>
<!-- Generated by lego_dualarm_description/scripts/generate_bricks.py; do not edit by hand. -->
<sdf version="1.9">
  <model name="{name}">
    <link name="brick">
      <inertial>
        <pose>0 0 {zc} 0 0 0</pose>
        <mass>{m:.6g}</mass>
        <inertia><ixx>{ixx:.4g}</ixx><ixy>0</ixy><ixz>0</ixz><iyy>{iyy:.4g}</iyy><iyz>0</iyz><izz>{izz:.4g}</izz></inertia>
      </inertial>
{under_xml}
      <visual name="v_body">
        <pose>0 0 {zc} 0 0 0</pose>
        <geometry><box><size>{sx:.4f} {sy:.4f} {HEIGHT}</size></box></geometry>
        {mat}
      </visual>
{stud_xml}
    </link>
  </model>
</sdf>
"""


def main():
    root = os.environ.get("LEGO_MODEL_DIR",
                          os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "models"))
    for w, l in TYPES:
        for color, rgb in COLORS.items():
            name = f"lego_brick_{w}x{l}_{color}"
            d = os.path.join(root, name)
            os.makedirs(d, exist_ok=True)
            with open(os.path.join(d, "model.sdf"), "w") as f:
                f.write(model_sdf(name, w, l, rgb))
            with open(os.path.join(d, "model.config"), "w") as f:
                f.write(f"""<?xml version="1.0"?>
<model>
  <name>{name}</name>
  <version>0.1</version>
  <sdf version="1.9">model.sdf</sdf>
  <description>LEGO {w}x{l} brick, {color}, real dimensions (generated).</description>
</model>
""")
            print("wrote", name)
    for w, l in BASEPLATES:
        name = f"lego_baseplate_{w}x{l}"
        d = os.path.join(root, name)
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "model.sdf"), "w") as f:
            f.write(baseplate_sdf(name, w, l))
        with open(os.path.join(d, "model.config"), "w") as f:
            f.write(f"""<?xml version="1.0"?>
<model>
  <name>{name}</name>
  <version>0.1</version>
  <sdf version="1.9">model.sdf</sdf>
  <description>Static LEGO baseplate, {w}x{l} studs, 3.2 mm (generated).</description>
</model>
""")
        print("wrote", name)


if __name__ == "__main__":
    main()
